// Core Orchestrator: Generate 10-Question Placement Diagnostic with 50+ alternatives
// ============================================================================

export interface PlacementGenerationParams {
  isKhatim: boolean;
  memorizedJuzRange?: { fromJuz: number; toJuz: number };
  actualReachedSurah?: number;
  startingDirection?: 'baqarah_to_nas' | 'nas_to_baqarah';
  weakSurahs?: number[];
  seenQuestionIds?: string[];
  questionCount?: number;
}

/**
 * Generates an authentic diagnostic placement test:
 * - Selects from vast pools with at least 50 alternatives per category.
 * - Shuffles completely at random.
 * - Prevents repetition with seenQuestionIds.
 * - Mathematically impossible for any two students to get the same test questions.
 */
export async function generatePlacementDiagnosticTest(
  params: PlacementGenerationParams
): Promise<QuestionBankItem[]> {
  const {
    isKhatim,
    memorizedJuzRange = { fromJuz: isKhatim ? 1 : 28, toJuz: 30 },
    startingDirection = 'nas_to_baqarah',
    weakSurahs = [],
    seenQuestionIds = [],
    questionCount = 10
  } = params;

  const seenSet = new Set(seenQuestionIds);
  const quranQuestions: QuestionBankItem[] = [];
  const tajweedQuestions: QuestionBankItem[] = [];

  const targetQuranCount = isKhatim ? 7 : 5;
  const targetTajweedCount = questionCount - targetQuranCount;

  // 1. SELECT TAJWEED QUESTIONS FROM 50+ ITEM BANK
  const shuffledTajweedBank = shuffleArray(AUTHENTIC_TAJWEED_BANK);
  for (const t of shuffledTajweedBank) {
    if (tajweedQuestions.length >= targetTajweedCount) break;
    if (seenSet.has(t.id)) continue;

    tajweedQuestions.push({
      questionId: t.id,
      skill: 'tajweed_rules',
      questionType: 'tajweed_rule',
      difficulty: t.difficulty,
      questionText: t.questionText,
      options: shuffleArray(t.options),
      correctAnswer: t.correctAnswer,
      explanation: t.explanation,
      surahNumber: t.surahNumber
    });
  }

  // Fallback if needed
  if (tajweedQuestions.length < targetTajweedCount) {
    for (const t of shuffledTajweedBank) {
      if (tajweedQuestions.length >= targetTajweedCount) break;
      if (!tajweedQuestions.some(item => item.questionId === t.id)) {
        tajweedQuestions.push({
          questionId: t.id,
          skill: 'tajweed_rules',
          questionType: 'tajweed_rule',
          difficulty: t.difficulty,
          questionText: t.questionText,
          options: shuffleArray(t.options),
          correctAnswer: t.correctAnswer,
          explanation: t.explanation,
          surahNumber: t.surahNumber
        });
      }
    }
  }

  // 2. SELECT QURAN & MUTASHABIHAT QUESTIONS (50+ BANK + 6236 VERSES GENERATOR)
  if (isKhatim) {
    // Khatim gets 3 Mutashabihat from the 50+ Mutashabihat bank + 3 diverse Quran questions
    const shuffledMut = shuffleArray(AUTHENTIC_MUTASHABIHAT);
    for (const m of shuffledMut) {
      if (quranQuestions.length >= 3) break;
      if (seenSet.has(m.id)) continue;

      quranQuestions.push({
        questionId: m.id,
        skill: 'mutashabihat',
        questionType: 'mutashabihat_distinction',
        difficulty: 'hard',
        surahNumber: m.surahNumber,
        ayahNumber: m.ayahNumber,
        questionText: `${m.verseExcerpt} - اختر التتمة القرآنية الدقيقة:`,
        options: shuffleArray(m.distractorPassages),
        correctAnswer: m.correctText,
        explanation: m.explanation
      });
    }

    // Diverse continuation / endings from across all 114 Surahs
    const randomSurahsPool = shuffleArray(Array.from({ length: 114 }, (_, i) => i + 1));
    for (const sNum of randomSurahsPool) {
      if (quranQuestions.length >= targetQuranCount) break;
      const sInfo = getSurahInfo(sNum);
      const randomAyah = Math.min(sInfo.numberOfAyahs, Math.max(1, Math.floor(Math.random() * sInfo.numberOfAyahs) + 1));
      
      const q = Math.random() > 0.5
        ? await createAuthenticVerseContinuationQuestion(sNum, randomAyah, 'medium')
        : await createAuthenticAyahEndingQuestion(sNum, randomAyah, 'medium');

      if (q && !seenSet.has(q.questionId) && !quranQuestions.some(item => item.questionId === q.questionId)) {
        quranQuestions.push(q);
      }
    }
  } else {
    // Non-Khatim: Questions strictly within memorized Juz or weak surahs
    const minJuz = Math.min(memorizedJuzRange.fromJuz, memorizedJuzRange.toJuz);
    const maxJuz = Math.max(memorizedJuzRange.fromJuz, memorizedJuzRange.toJuz);

    // Eligible surahs in range
    const eligibleSurahs: number[] = [];
    if (weakSurahs && weakSurahs.length > 0) {
      eligibleSurahs.push(...weakSurahs);
    }

    // Default: Surahs 78 to 114 for Juz 30/29/28, or custom range
    for (let s = 1; s <= 114; s++) {
      const sInfo = getSurahInfo(s);
      if (sInfo.juz >= minJuz && sInfo.juz <= maxJuz) {
        if (!eligibleSurahs.includes(s)) eligibleSurahs.push(s);
      }
    }
    if (eligibleSurahs.length === 0) {
      // Default to Amma & Tabarak
      for (let s = 67; s <= 114; s++) eligibleSurahs.push(s);
    }

    // Pull from authentic Mutashabihat within this scope if available
    const scopeMutashabihat = AUTHENTIC_MUTASHABIHAT.filter(m => eligibleSurahs.includes(m.surahNumber));
    for (const m of shuffleArray(scopeMutashabihat)) {
      if (quranQuestions.length >= 2) break;
      if (seenSet.has(m.id)) continue;
      quranQuestions.push({
        questionId: m.id,
        skill: 'mutashabihat',
        questionType: 'mutashabihat_distinction',
        difficulty: 'medium',
        surahNumber: m.surahNumber,
        ayahNumber: m.ayahNumber,
        questionText: `${m.verseExcerpt} - اختر التتمة القرآنية الدقيقة:`,
        options: shuffleArray(m.distractorPassages),
        correctAnswer: m.correctText,
        explanation: m.explanation
      });
    }

    // Generate remaining from verses of eligible surahs
    for (const sNum of shuffleArray(eligibleSurahs)) {
      if (quranQuestions.length >= targetQuranCount) break;
      const sInfo = getSurahInfo(sNum);
      const randomAyah = Math.min(sInfo.numberOfAyahs, Math.max(1, Math.floor(Math.random() * sInfo.numberOfAyahs) + 1));
      
      const q = Math.random() > 0.5
        ? await createAuthenticVerseContinuationQuestion(sNum, randomAyah, 'medium')
        : await createAuthenticIdentifySurahQuestion(sNum, randomAyah, 'easy');

      if (q && !seenSet.has(q.questionId) && !quranQuestions.some(item => item.questionId === q.questionId)) {
        quranQuestions.push(q);
      }
    }
  }

  // Combine & Shuffle the final 10 questions
  const finalTest = shuffleArray([...quranQuestions, ...tajweedQuestions]).slice(0, questionCount);
  return finalTest;
}

// ============================================================================
// Multi-Dimensional Placement Scoring & Classification
// ============================================================================
export interface EvaluationInput {
  answers: PlacementQuestionResult[];
  isKhatim: boolean;
  studentInfo?: {
    weakSurahs?: number[];
    startingYear?: string;
    previousDirection?: string;
    healthOrEducationalNotes?: string;
  };
}

export function evaluatePlacementDiagnostic(input: EvaluationInput): PlacementTestSummary {
  const { answers, isKhatim } = input;
  const totalQuestions = answers.length || 10;
  const correctCount = answers.filter(a => a.isCorrect).length;
  const overallPercentage = Math.round((correctCount / totalQuestions) * 100);

  // Skill breakdowns
  const quranAnswers = answers.filter(a => a.skill === 'quran_memorization');
  const tajweedAnswers = answers.filter(a => a.skill === 'tajweed_rules');
  const mutashabihatAnswers = answers.filter(a => a.skill === 'mutashabihat');

  const quranCorrect = quranAnswers.filter(a => a.isCorrect).length;
  const tajweedCorrect = tajweedAnswers.filter(a => a.isCorrect).length;
  const mutCorrect = mutashabihatAnswers.filter(a => a.isCorrect).length;

  const quranScore = quranAnswers.length > 0 ? Math.round((quranCorrect / quranAnswers.length) * 100) : overallPercentage;
  const tajweedScore = tajweedAnswers.length > 0 ? Math.round((tajweedCorrect / tajweedAnswers.length) * 100) : overallPercentage;
  const mutashabihatScore = mutashabihatAnswers.length > 0 ? Math.round((mutCorrect / mutashabihatAnswers.length) * 100) : overallPercentage;

  // Determine Level according to pedagogical criteria
  let level: 'مبتدئ' | 'متوسط' | 'متقدم' | 'خاتم ومتقن' = 'متوسط';
  let levelCategory: 'خاتم متقن' | 'خاتم يحتاج تثبيت' | 'حافظ متقدم' | 'حافظ متوسط' | 'مبتدئ' | 'تأسيس وتصحيح' = 'حافظ متوسط';
  let pedagogicalNotes = '';

  if (isKhatim) {
    if (overallPercentage >= 85 && tajweedScore >= 80 && mutashabihatScore >= 80) {
      level = 'خاتم ومتقن';
      levelCategory = 'خاتم متقن';
      pedagogicalNotes = 'ما شاء الله تبارك الله، الطالب متقن لأحكام التجويد ومواضع المتشابهات ومؤهل للإجازة والسند.';
    } else {
      level = 'متقدم';
      levelCategory = 'خاتم يحتاج تثبيت';
      pedagogicalNotes = 'الطالب حافظ للقرآن الكريم كاملاً، لكنه بحاجة لتركيز مضاعف على المتشابهات اللفظية وتثبيت فواصل الآيات.';
    }
  } else {
    if (overallPercentage >= 80 && tajweedScore >= 75) {
      level = 'متقدم';
      levelCategory = 'حافظ متقدم';
      pedagogicalNotes = 'استحضار ممتاز ومخارج حروف متقنة؛ مؤهل لمسار تثبيت موسع وسريع.';
    } else if (overallPercentage >= 50) {
      level = 'متوسط';
      levelCategory = 'حافظ متوسط';
      pedagogicalNotes = 'مستوى متوازن في الحفظ والأحكام، يوصى بمسار التثبيت المتزن قبل زيادة وتيرة الحفظ الجديد.';
    } else {
      level = 'مبتدئ';
      levelCategory = 'تأسيس وتصحيح';
      pedagogicalNotes = 'يحتاج إلى تصحيح التلاوة والتدرج في قصار السور مع تقوية أحكام النون والميم والمدود.';
    }
  }

  const incorrectCount = totalQuestions - correctCount;

  return {
    totalQuestions,
    correctCount,
    incorrectCount,
    timeoutCount: answers.filter(a => a.isTimedOut).length,
    memorizationScore: quranScore,
    retentionScore: quranScore,
    tajweedScore,
    overallScore: overallPercentage,
    levelClassification: level,
    classifiedLevel: level,
    confidenceRating: 'high',
    recommendations: [pedagogicalNotes]
  };
}
